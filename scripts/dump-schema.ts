/**
 * dump-schema — compile ALL migrations into a standalone `db/schema.sql` (MariaDB dialect).
 *
 * Uses Kysely's DummyDriver (no live DB needed) + a recording driver that captures
 * every compiled statement, then runs migrations/000*.ts in order against it.
 *
 * Usage:  npm run schema:dump      (== npx tsx scripts/dump-schema.ts)
 * Output: db/schema.sql            (import via phpMyAdmin or `mysql` CLI)
 */
import fs from 'node:fs';
import path from 'node:path';
import {
  DummyDriver,
  Kysely,
  MysqlAdapter,
  MysqlIntrospector,
  MysqlQueryCompiler,
  type CompiledQuery,
  type DatabaseConnection,
  type QueryResult,
} from 'kysely';

class RecordingDriver extends DummyDriver {
  constructor(private readonly statements: string[]) {
    super();
  }

  override async acquireConnection(): Promise<DatabaseConnection> {
    const statements = this.statements;
    return {
      executeQuery: async <R>(compiledQuery: CompiledQuery): Promise<QueryResult<R>> => {
        statements.push(compiledQuery.sql);
        return { rows: [] };
      },
      // eslint-disable-next-line @typescript-eslint/no-unused-vars
      streamQuery: async function* <R>(
        _compiledQuery: CompiledQuery,
        _chunkSize: number,
      ): AsyncIterableIterator<QueryResult<R>> {
        // no rows in dump mode
      },
    };
  }
}

async function main(): Promise<void> {
  const statements: string[] = [];
  const db = new Kysely<any>({
    dialect: {
      createAdapter: () => new MysqlAdapter(),
      createDriver: () => new RecordingDriver(statements),
      createIntrospector: (d) => new MysqlIntrospector(d),
      createQueryCompiler: () => new MysqlQueryCompiler(),
    },
  });

  // جدول bookkeeping (معادل ensureMigrationsTable در src/core/db/migrate.ts)
  await db.schema
    .createTable('migrations')
    .ifNotExists()
    .addColumn('name', 'varchar(255)', (c) => c.primaryKey())
    .addColumn('executed_at', 'varchar(32)', (c) => c.notNull())
    .execute();

  const dir = path.join(__dirname, '..', 'migrations');
  const files = fs
    .readdirSync(dir)
    .filter((f) => /^\d+.*\.ts$/.test(f))
    .sort();

  for (const file of files) {
    const mod = (await import(path.join(dir, file))) as {
      up: (db: Kysely<any>, ctx: { dialect: 'mysql' }) => Promise<void>;
    };
    if (typeof mod.up !== 'function') {
      throw new Error(`migration ${file} تابع up ندارد`);
    }
    await mod.up(db, { dialect: 'mysql' });
  }

  const header = [
    '-- myclass — schema dump (MariaDB / MySQL dialect)',
    '-- Generated by: npm run schema:dump  (scripts/dump-schema.ts)',
    `-- Migrations applied in order: ${files.length}`,
    '-- Safe to import via phpMyAdmin or the mysql CLI on a fresh, empty database.',
    '',
  ].join('\n');
  const body = statements.map((s) => s.trim().replace(/;$/, '') + ';').join('\n\n');

  const out = path.join(__dirname, '..', 'db', 'schema.sql');
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, header + body + '\n', 'utf8');
  console.log(
    `schema dump: ${files.length} migrations, ${statements.length} statements -> ${path.relative(process.cwd(), out)}`,
  );
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
